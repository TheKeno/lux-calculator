// Extracts photometric data from fixture PDF reports into fixtures.js.
//
// Usage:  node tools/extract-fixtures.mjs [pdfDir]
// Requires `pdftotext` (poppler) on PATH — Git for Windows ships it in mingw64/bin.
//
// Expects "Type C" photometric reports with a "Candlepower Table" (rows G0..G180,
// columns C0 C90 C180 C270 C360, unit cd), like the Luxibel XFL300TW reports.

import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { join, basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pdfDir = resolve(process.argv[2] ?? root);
const outFile = join(root, "fixtures.js");

const num = (re, text) => {
  const m = text.match(re);
  return m ? parseFloat(m[1]) : null;
};

function parsePdf(file) {
  const text = execFileSync("pdftotext", ["-layout", file, "-"], { encoding: "latin1", maxBuffer: 1 << 26 });
  const pages = text.split("\f");

  const first = pages[0];
  const name = (first.match(/Report No\.:\s*(\S+)/) || [])[1] ?? basename(file, ".pdf");
  const manufacturer = ((first.match(/Manufacturer:\s*(.+?)\s*$/m) || [])[1] ?? "").trim();

  const fixture = {
    id: name,
    name,
    manufacturer,
    source: basename(file),
    powerW: num(/Power:\s*([\d.]+)\s*W/, first),
    lumens: num(/Total Rated Lamp Lumens:\s*([\d.]+)/, first),
    maxIntensityCd: num(/Max\. Intensity:\s*([\d.]+)/, first),
    beamAngle: num(/Vertical Diffuse Angle\(10%,50%,80%,100%\):\s*V[\d.]+,V([\d.]+)/, first),
    fieldAngle: num(/Vertical Diffuse Angle\(10%,50%,80%,100%\):\s*V([\d.]+)/, first),
    cPlanes: null,
    gammas: [],
    candela: [], // candela[cIndex][gammaIndex]
  };

  for (const page of pages) {
    if (!/Candlepower Table/.test(page)) continue;
    const lines = page.split(/\r?\n/);
    const header = lines.find((l) => /G\\C/.test(l));
    const planes = [...header.matchAll(/C([\d.]+)/g)].map((m) => parseFloat(m[1]));
    if (!fixture.cPlanes) {
      fixture.cPlanes = planes;
      fixture.candela = planes.map(() => []);
    }

    // Gamma labels and value rows are collected separately and zipped, because
    // pdftotext sometimes puts a row's values on the line after its label.
    const labels = [];
    const rows = [];
    for (const line of lines) {
      const m = line.match(/^\s*G([\d.]+)\s*(.*)$/);
      const rest = m ? m[2] : line;
      if (m) labels.push(parseFloat(m[1]));
      const vals = rest.trim().split(/\s+/).filter(Boolean).map(Number);
      if (vals.length === planes.length && vals.every((v) => Number.isFinite(v))) rows.push(vals);
    }
    if (labels.length !== rows.length) {
      throw new Error(`${file}: ${labels.length} gamma labels but ${rows.length} value rows on a candlepower page`);
    }
    labels.forEach((g, i) => {
      fixture.gammas.push(g);
      rows[i].forEach((v, c) => fixture.candela[c].push(v));
    });
  }

  if (!fixture.cPlanes || fixture.gammas.length === 0) throw new Error(`${file}: no candlepower table found`);

  // Trim trailing all-zero gammas to keep the file small.
  let last = fixture.gammas.length - 1;
  while (last > 0 && fixture.candela.every((col) => col[last] === 0)) last--;
  const keep = Math.min(fixture.gammas.length, last + 2);
  fixture.gammas = fixture.gammas.slice(0, keep);
  fixture.candela = fixture.candela.map((col) => col.slice(0, keep));
  return fixture;
}

const pdfs = readdirSync(pdfDir).filter((f) => f.toLowerCase().endsWith(".pdf")).sort();
const fixtures = [];
for (const f of pdfs) {
  try {
    const fx = parsePdf(join(pdfDir, f));
    fixtures.push(fx);
    console.log(`✓ ${f}: ${fx.name}, ${fx.lumens} lm, ${fx.gammas.length} gammas × ${fx.cPlanes.length} C-planes`);
  } catch (e) {
    console.warn(`✗ ${f}: ${e.message}`);
  }
}

writeFileSync(
  outFile,
  "// Generated by tools/extract-fixtures.mjs — do not edit by hand.\n" +
    "window.FIXTURES = " + JSON.stringify(fixtures) + ";\n"
);
console.log(`Wrote ${fixtures.length} fixture(s) to ${outFile}`);
